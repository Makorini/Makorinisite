/* Idioma atual: salvo no navegador; na 1ª visita segue o idioma do navegador. */
window.getLang = function () {
    try {
        const saved = localStorage.getItem("makorini-lang");
        if (saved === "pt" || saved === "en") return saved;
    } catch (e) {}
    return (navigator.language || "pt").toLowerCase().startsWith("pt") ? "pt" : "en";
};
window.t = function (key) {
    const lang = window.getLang();
    return (window.I18N[lang] && window.I18N[lang][key]) || window.I18N.pt[key] || key;
};
